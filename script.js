function mouseOver(link) {
    link.style.color = "red";
}
function mouseOut(link) {
    link.style.color = "white";
}
function imageOver(img) {
    img.style.transform = "scale(1.1)";
}
function imageOut(img) {
    img.style.transform = "scale(1)";
}
